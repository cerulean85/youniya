/** 43–46 Policy documents view (iOS PolicyDocView) */
@Composable
fun PolicyDocView(
    doc: PolicyDoc,
    onBack: () -> Unit,
    modifier: Modifier = Modifier,
) {
    BackHandler(onBack = onBack)
    Box(modifier.fillMaxSize()) {
        StarField()
        Column(Modifier.fillMaxSize().safeDrawingPadding()) {
            TopAppBar(title = doc.barTitle, onBack = onBack)

            Column(
                modifier = Modifier
                    .weight(1f)
                    .fillMaxWidth()
                    .verticalScroll(rememberScrollState())
                    .padding(horizontal = Space.xl)
                    .padding(top = Space.sm, bottom = Space.xxxl),
                verticalArrangement = Arrangement.spacedBy(Space.xl),
            ) {
                Text(
                    doc.title,
                    style = YText.h1,
                    color = YColor.textPrimary,
                    modifier = Modifier.semantics { heading() },
                )
                Text(
                    doc.effectiveDate,
                    style = YText.caption,
                    color = YColor.textSecondary,
                )

                doc.sections.forEach { (heading, body) ->
                    Column(
                        verticalArrangement = Arrangement.spacedBy(Space.sm),
                        modifier = Modifier.fillMaxWidth(),
                    ) {
                        Text(
                            heading,
                            style = YText.h3,
                            color = YColor.textPrimary,
                            modifier = Modifier.semantics { heading() },
                        )
                        Text(
                            body,
                            style = YText.bodyM,
                            color = YColor.textSecondary,
                        )
                    }
                }
            }
        }
    }
}
